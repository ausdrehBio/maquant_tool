"""Run q01 to q10 and write analysis_of_results/answers.md.

Run run_msstats.R first; q05 to q10 read its output in analysis_of_results/msstats/.
Usage (from any directory):  python3 <path to>/scripts/run_all.py
"""
import importlib

import mq_common as mq

MODULES = [
    "q01_proteins_features_total",
    "q02_contaminant_columns",
    "q03_contaminant_proportion",
    "q04_nonhuman_contaminants_removed",
    "q05_proteins_in_statistics",
    "q06_proteins_per_sample",
    "q07_features_per_protein",
    "q08_adjusted_pvalue",
    "q09_significant_proteins",
    "q10_differential_proteins",
]
TUTORIAL_URL = ("https://training.galaxyproject.org/topics/proteomics/tutorials/"
                "maxquant-msstats-dda-lfq/tutorial.html")


def comparison(results):
    info = mq.msstats_info()
    rows = [(f"Q{i}", m.TUTORIAL, ans.short, m.NOTE) for i, (m, ans) in enumerate(results, 1)]
    return [
        "## Comparison with the Galaxy tutorial",
        "",
        f"Published answers of the Galaxy Training Network tutorial "
        f"[MaxQuant and MSstats for the analysis of label-free data]({TUTORIAL_URL}) "
        "(MaxQuant 2.0.3 and MSstats 4.0.0 in Galaxy), next to this analysis "
        f"(MaxQuant {mq.maxquant_version()} and MSstats {info.get('MSstats', 'version unknown')}). "
        "Both MaxQuant and MSstats versions differ, so counts after identification and "
        "statistics can differ by a few percent.",
        "",
        mq.md_table(rows, ["", "Tutorial", "This analysis", "Note"]),
        "",
    ]


def main():
    parts = [
        "# tutorial_galaxy_2: answers",
        "",
        "Generated by `scripts/run_all.py` from the MaxQuant output in `results/combined/txt/` "
        "and the MSstats output of `scripts/run_msstats.R` in `msstats/`. Do not edit by hand, "
        "rerun the scripts. Definitions are documented in `scripts/mq_common.py`. Figures are "
        "written to `figures/`, which is not in git. A comparison with the tutorial's answers "
        "is at the end.",
        "",
    ]
    results = []
    for i, name in enumerate(MODULES, 1):
        module = importlib.import_module(name)
        print(f"\n=== Q{i}. {module.QUESTION}")
        ans = module.main()
        print(ans)
        results.append((module, ans))
        parts += [f"## Q{i}. {module.QUESTION}", "", str(ans), ""]
    parts += comparison(results)
    out = mq.OUT_DIR / "answers.md"
    out.write_text("\n".join(parts))
    print(f"answers written: {mq.rel(out)}")


if __name__ == "__main__":
    main()
