"""Run q01 to q07 and write analysis_of_results/answers.md.

Run run_msstats.R first; q06 and q07 read its output in analysis_of_results/msstats/.
Usage (from any directory):  python3 <path to>/scripts/run_all.py
"""
import importlib

import mq_common as mq

MODULES = [
    "q01_identifications",
    "q02_quantification",
    "q03_contaminants",
    "q04_technical_replicates",
    "q05_pca",
    "q06_differential",
    "q07_paper_proteins",
]
PAPER_REF = ("Liljedahl L, Norlin J, McGuire JN, James P (2017). Effects of insulin and the "
             "glucagon-like peptide 1 receptor agonist liraglutide on the kidney proteome in "
             "db/db mice. Physiol Rep 5(6):e13187, doi:10.14814/phy2.13187")


def comparison(results):
    info = mq.msstats_info()
    rows = [(f"Q{i}", m.PAPER, ans.short, m.NOTE) for i, (m, ans) in enumerate(results, 1)]
    return [
        "## Comparison with the publication",
        "",
        f"{PAPER_REF}. The paper analysed the same raw files (PRIDE PXD002988) with Progenesis "
        "QI and Mascot (UniProt mouse 2013.05, 5% FDR), SIMCA for multivariate analysis and "
        "one-way ANOVA with Tukey in GraphPad Prism. This analysis uses "
        f"MaxQuant {mq.maxquant_version()} (Swiss-Prot canonical mouse, 1% FDR, LFQ, match "
        f"between runs) and MSstats {info.get('MSstats', 'version unknown')}, so counts and "
        "p-values are not expected to be identical.",
        "",
        mq.md_table(rows, ["", "Paper", "This analysis", "Note"]),
        "",
    ]


def main():
    parts = [
        "# Liljedahl_2017: answers",
        "",
        "Generated by `scripts/run_all.py` from the MaxQuant output in `results/combined/txt/` "
        "and the MSstats output of `scripts/run_msstats.R` in `msstats/`. Do not edit by hand, "
        "rerun the scripts. Definitions (groups, clean set, thresholds) are documented in "
        "`scripts/mq_common.py`. Figures are written to `figures/`, which is not in git. A "
        "comparison with the paper is at the end.",
        "",
        "Groups (5 mice each, 2 technical replicates per mouse, 40 runs): "
        + ", ".join(f"{c} = {mq.CONDITION_LABELS[c]}" for c in mq.CONDITIONS) + ".",
        "",
    ]
    results = []
    for i, name in enumerate(MODULES, 1):
        module = importlib.import_module(name)
        print(f"\n=== Q{i}. {module.QUESTION}")
        ans = module.main()
        print(ans)
        results.append((module, ans))
        parts += [f"## Q{i}. {module.QUESTION}", "", str(ans), ""]
    parts += comparison(results)
    out = mq.OUT_DIR / "answers.md"
    out.write_text("\n".join(parts))
    print(f"answers written: {mq.rel(out)}")


if __name__ == "__main__":
    main()
