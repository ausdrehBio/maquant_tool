"""Run q01 to q08 and write analysis_of_results/answers.md and verdicts.tsv.

Needs annotation/ (written once by make_annotation.py) and the published table in
data/deposited/ (get_data_Bergant_2023.sh). Usage (from any directory, not with python3 -I):
    python3 <path to>/scripts/run_all.py
BG_SEEDS=10 makes a quick test run with 10 instead of 100 imputation seeds.
"""
import importlib
import json
import time

import mq_common as mq
import summary_plots

MODULES = [
    "q01_parameters",
    "q02_sample_assignment",
    "q03_identifications",
    "q04_quantitative_agreement",
    "q05_statistics_reimplementation",
    "q06_differential_agreement",
    "q07_sample_structure",
    "q08_paper_claims",
]


def overall(results):
    counts = {v: sum(a.verdict == v for _, a in results) for v in mq.VERDICTS}
    lines = [
        f"**Overall: {counts['consistent']} of {len(results)} checks consistent, "
        f"{counts['minor deviation']} with a minor deviation, {counts['inconsistent']} "
        "inconsistent.**",
    ]
    if counts["inconsistent"]:
        bad = ", ".join(f"Q{i}" for i, (_, a) in enumerate(results, 1) if a.verdict == "inconsistent")
        lines.append(f"The workflow does not reproduce the publication in {bad}; see these "
                     "sections before using the results.")
    elif counts["minor deviation"]:
        minor = ", ".join(f"Q{i}" for i, (_, a) in enumerate(results, 1)
                          if a.verdict == "minor deviation")
        lines.append(f"The workflow reproduces the publication; the minor deviations ({minor}) "
                     "are explained in their sections.")
    else:
        lines.append("The workflow reproduces the publication within the variation that the "
                     "authors' own deposited search shows.")
    return lines


def main():
    start = time.time()
    mq.selftest()
    results = []
    for i, name in enumerate(MODULES, 1):
        module = importlib.import_module(name)
        print(f"\n=== Q{i}. {module.QUESTION}")
        ans = module.main()
        print(f"verdict: {ans.verdict}; {ans.short}")
        results.append((module, ans))

    has67 = mq.has_ours67()
    ver = mq.versions()
    fig_verdicts, fig_compare = summary_plots.make(results)
    parts = [
        "# Bergant_2023: does our workflow reproduce the published results?",
        "",
        "Generated by `scripts/run_all.py`. Do not edit by hand; rerun the scripts. Definitions "
        "(layers, matching, the paper pipeline, verdict rules) are documented in "
        "`scripts/mq_common.py`; figures are written to `figures/` and per-protein tables to "
        "`tables/`, both not in git.",
        "",
        f"Publication: {mq.PAPER_REF}. Data: PRIDE PXD040456, dataset IAV_FPMS (A549 cells, mock "
        "or infected with six PR8 NS1 mutants at MOI 3 for 24 h, 6 replicates each, 42 runs).",
        "",
        "Compared: **ours** (MaxQuant "
        f"{mq.ours().version}, the paper's 42 runs, results/combined/txt), **deposited** (the "
        "authors' MaxQuant 1.5.6.2 proteinGroups, 67 runs), **published** (Supplementary Data 5: "
        "the filtered, imputed matrix with the paper's statistics, from a search that is not "
        "deposited)"
        + (", and **ours-67** (MaxQuant 2.9.0 on all 67 runs, Part B)" if has67 else "")
        + f". Imputation seeds: {mq.N_SEEDS} (np.random.SeedSequence root {mq.SEED_ROOT}).",
        "",
        "Conditions: " + "; ".join(f"{c} = {mq.CONDITION_LABELS[c]}" for c in mq.CONDITIONS) + ".",
        "",
        "## Summary",
        "",
        *overall(results),
        "",
        mq.md_table([(f"Q{i}", m.QUESTION, a.verdict, a.short) for i, (m, a) in enumerate(results, 1)],
                    ["", "Question", "Verdict", "Key result"]),
        "",
        "Each check against its verdict rule: our value (blue) in the zones of the rule, next to "
        "the authors' own deposited search (orange) where the rule compares with it:",
        "",
        f"![Verdict overview]({fig_verdicts})",
        "",
        "The same comparison metric by metric: our result divided by the authors' deposited "
        "search, so 1 means our workflow does exactly as well as the authors' own MaxQuant output:",
        "",
        f"![Ours next to the authors' reanalysis]({fig_compare})",
        "",
    ]
    for i, (module, ans) in enumerate(results, 1):
        parts += [f"## Q{i}. {module.QUESTION}", "", str(ans), ""]
    parts += [
        "## Comparison with the publication",
        "",
        mq.md_table([(f"Q{i}", m.PAPER, a.short, m.NOTE) for i, (m, a) in enumerate(results, 1)],
                    ["", "Paper", "This analysis", "Note"]),
        "",
        "## Limitations",
        "",
        "- The published table (Supplementary Data 5) comes from a MaxQuant search that is not "
        "deposited (versioned Ensembl IDs, fewer missing values). It is compared at the level of "
        "the published analysis; the deposited proteinGroups serves as the authors' baseline.",
        "- Our search used the paper's 42 runs, the deposited one all 67. "
        + ("Part B (ours-67) separates the version effect from the run-set effect."
           if has67 else "Until Part B (MaxQuant 2.9.0 on all 67 runs) has run, the version "
           "effect cannot be separated from the run-set effect."),
        "- Imputation is random; results are medians and ranges over the seeds, and published "
        "outcomes that depend on the authors' single draw are reported, not judged (Q8).",
        "- The GO:0051607 set and the gene symbols come from a dated annotation snapshot "
        "(annotation/), not from the authors' annotation version.",
        "- The strains carry different NS1 sequences while the database holds only wild-type PR8 "
        "NS1, so NS1 quantities partly reflect peptide coverage (Q2, Q8).",
        "",
        "## Software",
        "",
        ", ".join(f"{k} {v}" for k, v in ver.items()) + f"; runtime {time.time() - start:.0f} s.",
        "",
    ]
    out = mq.OUT_DIR / "answers.md"
    out.write_text("\n".join(parts))
    print(f"\nanswers written: {mq.rel(out)}")
    tsv = mq.OUT_DIR / "verdicts.tsv"
    with open(tsv, "w") as fh:
        fh.write("question\tverdict\tkey_result\tmetrics\n")
        for i, (m, a) in enumerate(results, 1):
            metrics = json.dumps(a.metrics, sort_keys=True, default=lambda x: float(x))
            fh.write(f"Q{i}\t{a.verdict}\t{a.short}\t{metrics}\n")
    print(f"verdicts written: {mq.rel(tsv)}")


if __name__ == "__main__":
    main()
