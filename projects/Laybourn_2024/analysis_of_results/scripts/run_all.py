"""Run q01 to q08 and write analysis_of_results/answers.md and verdicts.tsv.

Needs the results of Laybourn_2024 (and, for Part B, of Laybourn_2024_depositedfasta,
Laybourn_2024_poollib and Laybourn_2024_pools), Table S3 in data/deposited/
(get_data_Laybourn_2024.sh) and annotation/ (written once by make_annotation.py). Usage (from
any directory, not with python3 -I):
    python3 <path to>/scripts/run_all.py
"""
import importlib
import json
import platform
import time

import matplotlib
import numpy as np
import openpyxl
import pandas as pd
import scipy

import lb_common as lb

PART_A = ["q01_parameters", "q02_sample_assignment", "q03_identifications",
          "q04_published_statistics", "q05_differential_agreement", "q06_paper_claims"]
PART_B = ["q07_viral_fasta", "q08_pool_library"]


def overall(results):
    counts = {v: sum(a.verdict == v for _, a in results) for v in lb.VERDICTS}
    return (f"**Part A: {counts['consistent']} of {len(results)} checks consistent, "
            f"{counts['minor deviation']} with a minor deviation, {counts['inconsistent']} "
            "inconsistent.**")


def findings(res):
    """Main findings, from the answers' metrics."""
    m = {name: a.metrics for name, a in res.items()}
    q2, q3, q5, q6, q7, q8 = (m.get(k, {}) for k in (
        "q02_sample_assignment", "q03_identifications", "q05_differential_agreement",
        "q06_paper_claims", "q07_viral_fasta", "q08_pool_library"))
    out = [
        f"- **The data and the design are the authors'.** Every swH1N1 sample is "
        f"virus-positive ({q2.get('sw_positive', '?')}/16; >= 2 viral precursors identified in "
        f"the run), while {q2.get('ctr_positive', '?')}/12 controls and "
        f"{q2.get('hu_positive', '?')}/16 huH1N1 samples are, and all infected samples show the "
        "interferon response (Q2). Our "
        "search finds as many "
        f"peptides as the paper ({lb.pct(q3.get('ratio_peptides'))}), fewer protein groups "
        f"({lb.pct(q3.get('ratio_groups'))}; protein inference differs, Q3).",
        "- **The biology of the interferon response reproduces**: MX1, MX2, ISG15 and IFI6 "
        "rise after both infections, viral protein is found after swH1N1 only, the upper "
        "trachea has more DEPs, and the lower trachea a larger share of antiviral DEPs (Q6).",
        f"- **The published DEP lists do not reproduce.** {lb.pct(q5.get('direction'), 0)} of "
        "the published DEPs that we quantify change in the same direction, but only "
        f"{lb.pct(q5.get('recall'), 0)} are DEPs in our data (Q5), and "
        f"{q6.get('reproduced', '?')} of {q6.get('parts', '?')} claim parts hold (Q6). The "
        "single-protein claims beyond the interferon response, mostly proteins that the "
        "authors saw in one group only, do not hold.",
        "- **The published statistics explain much of this.** Missing values were set to 0 and "
        "the tests were not corrected across proteins (Q4); on our data, random group labels "
        f"produce {lb.pct(q5.get('random_label_share'), 0)} as many DEPs as the real ones. "
        "Even our own searches of the same raw files agree only partly: "
        f"{lb.pct(q7.get('dep_overlap'), 0)} of the DEPs recur with the deposited viral FASTA "
        f"(Q7) and {lb.pct(q8.get('dep_overlap'), 0)} with the pool library (Q8). Lists made "
        "this way cannot be expected to agree protein by protein between analyses.",
    ]
    return out


def main():
    start = time.time()
    lb.selftest()
    results, part_b = [], []
    for i, name in enumerate(PART_A + PART_B, 1):
        module = importlib.import_module(name)
        print(f"\n=== Q{i}. {module.QUESTION}")
        ans = module.main()
        print(f"verdict: {ans.verdict}; {ans.short}")
        (results if name in PART_A else part_b).append((module, ans))
    res = {m.__name__: a for m, a in results + part_b}

    versions = {s: lb.maxquant_version(lb.search(s).txt_dir) for s in lb.available_searches()}
    sw = {"python": platform.python_version(), "pandas": pd.__version__, "numpy": np.__version__,
          "scipy": scipy.__version__, "matplotlib": matplotlib.__version__,
          "openpyxl": openpyxl.__version__}
    n_a = len(results)
    parts = [
        "# Laybourn_2024: does our workflow reproduce the published results?",
        "",
        "Generated by `scripts/run_all.py`. Do not edit by hand; rerun the scripts. Definitions "
        "(searches, layers, the reconstructed paper pipeline, matching, verdict rules) are "
        "documented in `scripts/lb_common.py`; figures are written to `figures/` and "
        "per-protein tables to `tables/`, both not in git.",
        "",
        f"Publication: {lb.PAPER_REF}. Data: PRIDE PXD052229 (Orbitrap Exploris 480, FAIMS, "
        "DIA; upper and lower trachea of 22 pigs 3 days after mock, swH1N1 or huH1N1 "
        "inoculation; 44 runs). The authors used Spectronaut 17.4; no protein matrix and no "
        "parameter file are deposited.",
        "",
        "Compared: **ours** (MaxQuant "
        f"{versions.get('ours', '?')} MaxDIA, library predicted from the FASTA files, "
        "results/combined/txt) in two layers, **as reported** and **run-filtered** (values "
        "only where the protein is identified in that run, as Spectronaut reports them), "
        "against **published** (Supplementary Table S3: the DEPs of six comparisons, and the "
        "paper's text). Part B compares two variants of our search: the viral FASTA files as "
        "deposited (../Laybourn_2024_depositedfasta) and a library from the pooled samples "
        "(../Laybourn_2024_poollib).",
        "",
        "Groups: ctr = mock-inoculated (pigs 1-6); sw = swH1N1, A/swine/Denmark/2017 (pigs "
        "7-14); hu = huH1N1, A/Denmark/238/2020 (pigs 19-26). Tissues: UT = upper, LT = lower "
        "trachea.",
        "",
        "## Summary",
        "",
        overall(results),
        "",
        *findings(res),
        "",
        lb.md_table([(f"Q{i}", m.QUESTION, a.verdict, a.short)
                     for i, (m, a) in enumerate(results, 1)],
                    ["", "Question", "Verdict", "Key result"]),
        "",
        "Part B, variants of our workflow (no verdict):",
        "",
        lb.md_table([(f"Q{i}", m.QUESTION, a.short)
                     for i, (m, a) in enumerate(part_b, n_a + 1)],
                    ["", "Question", "Key result"]),
        "",
        "# Part A: reproduction",
        "",
    ]
    for i, (module, ans) in enumerate(results, 1):
        parts += [f"## Q{i}. {module.QUESTION}", "", str(ans), ""]
    parts += ["# Part B: variants of our workflow", ""]
    for i, (module, ans) in enumerate(part_b, n_a + 1):
        parts += [f"## Q{i}. {module.QUESTION}", "", str(ans), ""]
    parts += [
        "## Comparison with the publication",
        "",
        lb.md_table([(f"Q{i}", m.PAPER, a.short, m.NOTE)
                     for i, (m, a) in enumerate(results + part_b, 1)],
                    ["", "Paper", "This analysis", "Note"]),
        "",
        "## Limitations",
        "",
        "- The authors deposited neither a protein matrix nor a Spectronaut report, so the "
        "comparison stops at the published DEP lists and the text; their statistics are "
        "reconstructed from Table S3 (Q4).",
        "- The run-filtered layer approximates Spectronaut's run-wise filtering with MaxDIA's "
        "precursor q-value and PEP per run. Spectronaut's own scoring, its protein-level "
        "run-wise q-value (0.05) and its protein quantities from filtered precursors are not "
        "reproduced; our protein quantities stay MaxQuant's LFQ.",
        "- Spectronaut and MaxQuant group proteins differently. A published accession is "
        "matched to the MaxQuant group that contains it, which for isoform-level groups of "
        "Spectronaut is a larger group with other quantities (Q5).",
        "- The pig numbering of the lower-trachea runs is inferred from the run numbers. The "
        "data confirm the group of every sample but not which pig of a group a lower-trachea "
        "sample comes from (Q2).",
        "- MaxDIA results differ between nearly identical searches (Q7): single proteins near "
        "the identification or significance thresholds can come out either way.",
        "- The GO:0051607 set is a current UniProt snapshot (annotation/), not the authors' "
        "annotation; it reproduces the published shares within 2 percentage points.",
        "- Claims about transcripts (RNA-seq, qPCR), histology and viral load are outside this "
        "reanalysis.",
        "",
        "## Software",
        "",
        "MaxQuant: " + ", ".join(f"{k} {v}" for k, v in versions.items()) + "; "
        + ", ".join(f"{k} {v}" for k, v in sw.items())
        + f"; runtime {time.time() - start:.0f} s.",
        "",
    ]
    out = lb.OUT_DIR / "answers.md"
    out.write_text("\n".join(parts))
    print(f"\nanswers written: {lb.rel(out)}")
    tsv = lb.OUT_DIR / "verdicts.tsv"
    with open(tsv, "w") as fh:
        fh.write("question\tverdict\tkey_result\tmetrics\n")
        for i, (m, a) in enumerate(results + part_b, 1):
            metrics = json.dumps(a.metrics, sort_keys=True, default=lambda x: float(x))
            fh.write(f"Q{i}\t{a.verdict or 'n/a (Part B)'}\t{a.short}\t{metrics}\n")
    print(f"verdicts written: {lb.rel(tsv)}")


if __name__ == "__main__":
    main()
