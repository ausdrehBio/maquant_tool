"""Run q01 to q12 and write analysis_of_results/answers.md.

Usage (from any directory):  python3 <path to>/scripts/run_all.py
Each q-script also runs on its own and prints its answer.
"""
import importlib

import mq_common as mq

MODULES = [
    "q01_total_proteins",
    "q02_total_peptides",
    "q03_identified_quantified",
    "q04_contaminants_per_sample",
    "q05_missed_cleavages",
    "q06_protein_ids_per_sample",
    "q07_decoys_removed",
    "q08_top5_abundant",
    "q09_depleted_sample",
    "q10_albumin_depletion",
    "q11_log2_intensity_boxplots",
    "q12_albumin_log2fc",
]


TUTORIAL_URL = "https://training.galaxyproject.org/topics/proteomics/tutorials/maxquant-label-free/tutorial.html"

WHY_INTENSITY = (
    "**Why Intensity instead of LFQ.** The tutorial bases Q3, Q8 and Q10 to Q12 on LFQ intensities. "
    "In MaxQuant 1.6.10 these exist even for proteins seen in only one sample, and they are barely "
    "normalised between the two samples, so they behave almost like raw intensities. MaxQuant 2.9.0 "
    "gives no LFQ value to proteins seen in one sample only, and its normalisation largely removes "
    "the global intensity shift that depletion causes. Abundance shares and the albumin fold change "
    "computed from 2.9.0 LFQ values are therefore not comparable with the tutorial; here, "
    "\"Intensity\" is the equivalent of the tutorial's LFQ columns. A one-off check against the "
    "tutorial's own MaxQuant output (Zenodo record 4274987) confirmed this: Intensity computed from "
    "that output gives nearly the same numbers as this run, and the tutorial's LFQ-based method "
    "reproduces its published answers there."
)


def comparison(results):
    rows = [(f"Q{i}", m.TUTORIAL, ans.short, m.NOTE) for i, (m, ans) in enumerate(results, 1)]
    return [
        "## Comparison with the Galaxy tutorial",
        "",
        f"Published answers of the Galaxy Training Network tutorial "
        f"[Label-free data analysis using MaxQuant]({TUTORIAL_URL}) (MaxQuant 1.6.10.43 in Galaxy), "
        "next to this run (MaxQuant 2.9.0). The MaxQuant parameters are the same as in the tutorial "
        "(see `parameter/mqpar.xml`).",
        "",
        mq.md_table(rows, ["", "Tutorial", "This run", "Note"]),
        "",
        WHY_INTENSITY,
        "",
    ]


def main():
    parts = [
        "# tutorial_galaxy: answers",
        "",
        "Generated by `scripts/run_all.py` from `results/combined/txt/` (MaxQuant 2.9.0). "
        "Do not edit by hand, rerun the script. Definitions (decoys, contaminants, clean set, "
        "top serum proteins) are documented in `scripts/mq_common.py`. "
        "Figures are written to `figures/`, which is not in git. "
        "A comparison with the Galaxy tutorial's answers is at the end.",
        "",
    ]
    results = []
    for i, name in enumerate(MODULES, 1):
        module = importlib.import_module(name)
        print(f"\n=== Q{i}. {module.QUESTION}")
        ans = module.main()
        print(ans)
        results.append((module, ans))
        parts += [f"## Q{i}. {module.QUESTION}", "", str(ans), ""]
    parts += comparison(results)
    out = mq.ANALYSIS_DIR / "answers.md"
    out.write_text("\n".join(parts))
    print(f"answers written: {mq.rel(out)}")


if __name__ == "__main__":
    main()
